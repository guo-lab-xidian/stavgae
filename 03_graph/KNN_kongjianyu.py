import pandas as pd
import numpy as np
from scipy.io import mmread, mmwrite
from scipy.sparse import coo_matrix
import logging

# 设置日志
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def read_interaction_matrix(file_path):
    interactions = mmread(file_path).tocoo()
    df = pd.DataFrame({
        "ligand_cell": interactions.row + 1,
        "receptor_cell": interactions.col + 1,
        "strength": interactions.data
    })
    return df


def read_distance_matrix(file_path):
    distances = pd.read_csv(file_path, index_col=0)
    distances.index = distances.index.astype(int)
    distances.columns = distances.columns.str.lstrip("X").astype(int)
    return distances.values  # 返回 NumPy array


def build_knn_graph_with_interactions(interactions_df, distance_matrix, k):
    num_cells = distance_matrix.shape[0]

    # 构建 {(ligand_cell, receptor_cell): strength} 字典
    interaction_dict = {
        (int(row['ligand_cell']), int(row['receptor_cell'])): float(row['strength'])
        for _, row in interactions_df.iterrows()
    }

    rows = []
    cols = []
    weights = []

    for i in range(num_cells):
        cell_i = i + 1
        distances = distance_matrix[i]
        nearest_indices = np.argsort(distances)  # 包括自己，不去掉 i 本身

        count = 0
        for j in nearest_indices:
            cell_j = j + 1
            if cell_j == cell_i and (cell_i, cell_i) not in interaction_dict:
                continue
            weight = 1.0 + interaction_dict.get((i + 1, j + 1), 0.0)  # 索引从0转为细胞编号从1
            rows.append(i + 1)
            cols.append(j + 1)
            weights.append(round(weight, 2))  # 保留两位小数
            count += 1
            if count >= k:
                break

    return pd.DataFrame({
        "ligand_cell": rows,
        "receptor_cell": cols,
        "strength": weights
    })

def save_sparse_matrix(df, file_path, num_cells):
    df = df.dropna()

    # 明确转换类型
    df["ligand_cell"] = df["ligand_cell"].astype(int)
    df["receptor_cell"] = df["receptor_cell"].astype(int)
    df["strength"] = df["strength"].astype(float).round(2)

    df = df.sort_values(['ligand_cell', 'receptor_cell'])

    with open(file_path, "w") as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python\n")
        f.write(f"{num_cells} {num_cells} {len(df)}\n")
        for _, row in df.iterrows():
            # ✅ 显式使用 int()，确保不会是 1.0 的格式
            f.write(f"{int(row['ligand_cell'])} {int(row['receptor_cell'])} {row['strength']:.2f}\n")



def main():
    #interaction_file = "C:/human_lungcancer/LRI_total/LRI_total_0.005.mtx"
    interaction_file = "D:/yxhu/空转/data/starmap/LRI_total/LRI_total_0.05.mtx"
    distance_matrix_file = r"D:\yxhu\空转\data\starmap\ccdistance\cell_distances_xuhao.csv"
    output_matrix_file = r"D:\yxhu\空转\data\starmap\KNN\k=40_p=0.05.mtx"
    logging.info("Reading files...")
    interactions_df = read_interaction_matrix(interaction_file)
    distance_matrix = read_distance_matrix(distance_matrix_file)

    logging.info("Building weighted KNN + interaction graph...")
    combined_graph_df = build_knn_graph_with_interactions(interactions_df, distance_matrix, k=40)

