import numpy as np
import pandas as pd
from scipy.io import mmread
import logging
import math

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def read_interaction_dict_mtx(mtx_path):
    """读取 LRI mtx -> dict: (ligand_cell, receptor_cell) -> strength，cell 索引为 1-based"""
    coo = mmread(mtx_path).tocoo()
    # 注意：MatrixMarket 读出来 row/col 是 0-based
    rows = (coo.row + 1).astype(np.int64)
    cols = (coo.col + 1).astype(np.int64)
    data = coo.data.astype(float)

    interaction_dict = {}
    for r, c, v in zip(rows, cols, data):
        interaction_dict[(int(r), int(c))] = float(v)
    return interaction_dict


def write_knn_interaction_mtx(
    interaction_dict,
    distance_matrix,
    k,
    out_mtx_path,
):
    """
    生成加权 KNN 图并直接写 MatrixMarket：
    weight = 1 + log(1 + strength)  (strength 不存在则为 0)
    - 若 self-edge 且不存在 (i,i) 自通讯，则跳过 self 并用其他邻居补齐，尽量保证每个 i 输出 k 条边
    """
    num_cells = distance_matrix.shape[0]
    k_eff = min(k, num_cells)  # 防止 k > n

    # 如果 num_cells > 1 且你希望严格每个点 k 条边，建议候选数取 k+1 或 k+5
    candidate_count = min(num_cells, k_eff + 5)

    # 这里我们尽量保证每个点输出 k_eff 条边（除非 num_cells 太小）
    nnz = num_cells * k_eff

    with open(out_mtx_path, "w") as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python (KNN + interaction)\n")
        f.write(f"{num_cells} {num_cells} {nnz}\n")

        for i in range(num_cells):
            cell_i = i + 1
            dist_i = distance_matrix[i]

            # 取前 candidate_count 个最小距离的索引（不全排序，快很多）
            cand_idx = np.argpartition(dist_i, candidate_count - 1)[:candidate_count]
            # 再按距离排序，保证最近的在前
            cand_idx = cand_idx[np.argsort(dist_i[cand_idx])]

            written = 0
            for j in cand_idx:
                cell_j = int(j + 1)

                # 如果是 self-edge 且没有自通讯，则跳过
                if cell_j == cell_i and (cell_i, cell_i) not in interaction_dict:
                    continue

                strength = interaction_dict.get((cell_i, cell_j), 0.0)
                weight = 1.0 + math.log1p(strength)  # log(1+strength)
                f.write(f"{cell_i} {cell_j} {weight:.2f}\n")
                written += 1

                if written >= k_eff:
                    break

            # 兜底：如果候选里不够写满（极少见：比如 num_cells 很小或候选不足），就用全体补齐
            if written < k_eff:
                all_idx = np.argsort(dist_i)
                for j in all_idx:
                    cell_j = int(j + 1)
                    if cell_j == cell_i and (cell_i, cell_i) not in interaction_dict:
                        continue
                    # 避免重复写：如果 cand_idx 已经覆盖，这里简单跳过也行（严格去重需要集合，会稍慢）
                    strength = interaction_dict.get((cell_i, cell_j), 0.0)
                    weight = 1.0 + math.log1p(strength)
                    f.write(f"{cell_i} {cell_j} {weight:.2f}\n")
                    written += 1
                    if written >= k_eff:
                        break

    logging.info(f"Saved: {out_mtx_path} (nnz={nnz}, k={k_eff}, n={num_cells})")


def main():
    interaction_file = r"D:\yxhu\空转\data\ovariancancer\LRI_total\LRI_total_0.005.mtx"
    distance_matrix_file = r"D:\yxhu\空转\data\ovariancancer\ccdistance\ovarian_dist_matrix_xuhao.npy"
    output_matrix_file = r"D:\yxhu\空转\data\ovariancancer\KNN\k=100\kongjianyu_k=100_noself.mtx"

    logging.info("Reading interaction mtx -> dict ...")
    interaction_dict = read_interaction_dict_mtx(interaction_file)

    logging.info("Loading distance matrix npy ...")
    distance_matrix = np.load(distance_matrix_file)

    logging.info("Building and writing KNN+interaction graph (streaming) ...")
    write_knn_interaction_mtx(
        interaction_dict=interaction_dict,
        distance_matrix=distance_matrix,
        k=100,
        out_mtx_path=output_matrix_file,
    )

    logging.info("All done.")


if __name__ == "__main__":
    main()
