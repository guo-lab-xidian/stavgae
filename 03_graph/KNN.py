import pandas as pd
import numpy as np
from scipy.io import mmread
import logging
from multiprocessing import Pool, cpu_count
import os

# 设置日志记录
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def read_interaction_matrix(file_path):
    interactions = mmread(file_path).tocoo()
    return coo_to_dataframe(interactions)
def coo_to_dataframe(coo):
    df = pd.DataFrame({
        "ligand_cell": coo.row + 1,
        "receptor_cell": coo.col + 1,
        "strength": coo.data
    })
    return df
def read_distance_matrix(file_path):
    distances = pd.read_csv(file_path, index_col=0)
    distances.columns = distances.columns.str.lstrip("X")
    return distances

def save_sparse_matrix(interactions, file_path, num_cells):
    interactions["ligand_cell"] = interactions["ligand_cell"].astype(int)
    interactions["receptor_cell"] = interactions["receptor_cell"].astype(int)
    interactions["strength"] = interactions["strength"].astype(float)

    num_interactions = len(interactions)

    with open(file_path, "w") as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python\n")
        f.write(f"{num_cells} {num_cells} {num_interactions}\n")
        for _, row in interactions.iterrows():
            f.write(f"{int(row['ligand_cell'])} {int(row['receptor_cell'])} {row['strength']:.2f}\n")

def save_results_to_csv(results_df, output_file):
    results_df.to_csv(output_file, index=False)
    logging.info(f"Statistics saved to {output_file}")

def process_single_cell(args):
    cell_id, interactions_df, distance_matrix, n_neighbors = args
    logging.info(f"正在处理 {cell_id}")

    # 获取距离最近的 n 个细胞
    distances = distance_matrix.loc[cell_id].sort_values()
    nearest_neighbors = distances.index[:n_neighbors].astype(int)

    # 当前细胞作为配体的所有行
    ligand_rows = interactions_df[interactions_df["ligand_cell"] == cell_id]

    # 当前细胞作为受体的所有行
    receptor_rows = interactions_df[interactions_df["receptor_cell"] == cell_id]
    receptor_rows = receptor_rows[receptor_rows["ligand_cell"] != cell_id]

    # 统计作为配体时与邻居的相互作用
    ligand_interactions = ligand_rows[ligand_rows["receptor_cell"].isin(nearest_neighbors)]

    # 统计作为受体时与邻居的相互作用
    receptor_interactions = receptor_rows[receptor_rows["ligand_cell"].isin(nearest_neighbors)]

    # 获取有相互作用的邻居 ID
    interacting_ligand_neighbors = ligand_interactions["receptor_cell"].values
    interacting_receptor_neighbors = receptor_interactions["ligand_cell"].values

    # 合并所有相互作用的细胞
    all_interacting_neighbors = np.concatenate([interacting_ligand_neighbors, interacting_receptor_neighbors])

    # 计算总的相互作用次数
    total_interactions = len(ligand_interactions) + len(receptor_interactions)

    return {
        "cell_id": cell_id,
        "total_neighbors": n_neighbors,
        "interaction_ratio": len(all_interacting_neighbors) / n_neighbors,
        "total_interactions": total_interactions,
        "filtered_interactions": pd.concat([ligand_interactions, receptor_interactions])
    }


def analyze_cell_interactions(interactions_df, distance_matrix, n_neighbors, output_matrix_file, output_csv_file):
    cell_ids = distance_matrix.index
    num_cells = len(cell_ids)

    # 准备多进程参数
    process_args = [(cell_id, interactions_df, distance_matrix, n_neighbors) for cell_id in cell_ids]

    # 使用进程池处理数据
    num_processes = max(1, cpu_count() - 1)  # 留出一个CPU核心
    logging.info(f"Starting multiprocessing with {num_processes} processes")

    with Pool(processes=num_processes) as pool:
        results = pool.map(process_single_cell, process_args)

    # 合并所有结果
    filtered_interactions = pd.concat([result["filtered_interactions"] for result in results])
    filtered_interactions = filtered_interactions.drop_duplicates()

    # 创建结果DataFrame
    results_df = pd.DataFrame([{
        "cell_id": result["cell_id"],
        "total_neighbors": result["total_neighbors"],
        "interaction_ratio": result["interaction_ratio"],
        "total_interactions": result["total_interactions"]
    } for result in results])

    # 保存结果
    save_sparse_matrix(filtered_interactions, output_matrix_file, num_cells)
    save_results_to_csv(results_df, output_csv_file)

    return results_df


def main():
    # 示例运行
    interaction_file = "D:/yxhu/空转/data/LRI_sparse_test/LRI_total2.mtx"
    distance_matrix_file = "D:/yxhu/空转/data/CCDistance/cell_distances2_xuhao.csv"
    output_matrix_file = "D:/yxhu/空转/data/KNN/k=100/cell1_as_ligand.mtx"
    output_csv_file = "D:/yxhu/空转/data/KNN/k=100/statistics.csv"

    logging.info("Reading input files...")
    interactions_df = read_interaction_matrix(interaction_file)
    distance_matrix = read_distance_matrix(distance_matrix_file)

    logging.info("Starting analysis...")
    results = analyze_cell_interactions(
        interactions_df,
        distance_matrix,
        100,
        output_matrix_file,
        output_csv_file
    )

    logging.info("Analysis completed")
