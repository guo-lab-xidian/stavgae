library(data.table)
library(parallel)
library(readr)

# 读取细胞通讯矩阵
read_interaction_matrix <- function(file_path) {
  interactions <- read.table(file_path, skip = 3, header = FALSE)
  colnames(interactions) <- c("ligand_cell", "receptor_cell", "strength")
  return(interactions)
}

# 读取距离矩阵
read_distance_matrix <- function(file_path) {
  distances <- read.csv(file_path, header = TRUE, row.names = 1)
  distance_matrix <- as.matrix(distances)
  colnames(distance_matrix) <- sub("^X", "", colnames(distance_matrix))
  return(distance_matrix)
}

# 分析每个细胞与最近邻居的相互作用
analyze_cell_interactions <- function(interactions_df, distance_matrix, n_neighbors, output_file) {
  # 获取细胞ID
  cell_ids <- rownames(distance_matrix)
  num_cells <- length(cell_ids)
  
  # 初始化用于存储筛选后的相互作用
  filtered_interactions <- data.frame(
    ligand_cell = integer(),
    receptor_cell = integer(),
    strength = numeric()
  )
  results <- data.frame(
    cell_id = character(),
    total_neighbors = integer(),
    interaction_ratio = numeric(),
    total_interactions = integer()  # 新增：总共的相互作用次数
  )
  
  for (cell_id in cell_ids) {
    
    # 获取距离最近的n个细胞
    distances <- distance_matrix[cell_id, ]
    nearest_neighbors <- names(sort(distances))
    nearest_neighbors <- nearest_neighbors[1:n_neighbors]  # 取前n个
    
    # 当前细胞作为配体的所有行
    ligand_rows <- interactions_df[interactions_df$ligand_cell == cell_id, ]
    # 当前细胞作为受体的所有行
    receptor_rows <- interactions_df[interactions_df$receptor_cell == cell_id, ]
    receptor_rows <- receptor_rows[receptor_rows$ligand_cell != cell_id, ]
    
    # 统计作为配体时与邻居的相互作用
    ligand_interactions <- ligand_rows[ligand_rows$receptor_cell %in% nearest_neighbors, ]
    # 统计作为受体时与邻居的相互作用
    receptor_interactions <- receptor_rows[receptor_rows$ligand_cell %in% nearest_neighbors, ]
    
    # 合并筛选后的相互作用
    filtered_interactions <- rbind(
      filtered_interactions,
      ligand_interactions[, c("ligand_cell", "receptor_cell", "strength")],
      receptor_interactions[, c("ligand_cell", "receptor_cell", "strength")]
    )
    # 获取有相互作用的邻居ID（不去重）
    interacting_ligand_neighbors <- ligand_interactions$receptor_cell
    interacting_receptor_neighbors <- receptor_interactions$ligand_cell
    
    # 合并所有相互作用的细胞（去重用于计算独特的相互作用细胞数）
    all_interacting_neighbors <- c(interacting_ligand_neighbors, interacting_receptor_neighbors)
    
    # 计算总的相互作用次数（包括重复）
    total_interactions <- nrow(ligand_interactions) + nrow(receptor_interactions)
    results <- rbind(results, data.frame(
      cell_id = cell_id,
      total_neighbors = n_neighbors,
      interaction_ratio = length(all_interacting_neighbors) / n_neighbors,
      total_interactions = total_interactions  # 总的相互作用次数
    ))
  }
  
  # 去重处理
  filtered_interactions <- unique(filtered_interactions)
  
  # 保存为稀疏矩阵格式
  save_sparse_matrix(filtered_interactions, output_file, num_cells)
  return(results)
}

# 保存为稀疏矩阵格式
save_sparse_matrix <- function(interactions, file_path, num_cells) {
  # 相互作用总数
  num_interactions <- nrow(interactions)
  
  # 构建 MatrixMarket 文件头
  header <- sprintf("%%MatrixMarket matrix coordinate real general\n%% Generated by R\n%d %d %d",
                    num_cells, num_cells, num_interactions)
  
  # 写入文件
  write(header, file = file_path)
  write.table(
    interactions,
    file = file_path,
    append = TRUE,  # 追加到头文件后面
    row.names = FALSE,
    col.names = FALSE,
    sep = " "
  )
}

