# === 保存统计结果为 CSV ===
def save_results_to_csv(results_df, output_file):
    results_df['cell_id'] = results_df['cell_id'].astype(int)
    results_df.to_csv(output_file, index=False)
    logging.info(f"Statistics saved to {output_file}")

# === 主分析函数 ===
def analyze_cell_interactions(
    interactions_df,
    distance_matrix,
    n_neighbors,
    output_matrix_file,
    output_csv_file
):
    num_cells = distance_matrix.shape[0]

    # ===== 结果统计（和你原来一样）=====
    results = []

    # ===== 稀疏矩阵三元组（逐步追加）=====
    rows, cols, data = [], [], []

    for cell_id in range(1, num_cells + 1):

        if cell_id % 500 == 0:
            logging.info(f"Processing cell {cell_id}/{num_cells}")

        # ---------- KNN ----------
        distances = distance_matrix[cell_id - 1]
        nearest_neighbors = np.argsort(distances)[:n_neighbors + 1] + 1  # 1-based

        # ---------- 只取和 cell_id 有关的通讯 ----------
        ligand_rows = interactions_df[
            interactions_df["ligand_cell"] == cell_id
        ]

        # 用 dict 是“局部的”，不会爆内存
        ligand_strength = dict(
            zip(ligand_rows["receptor_cell"], ligand_rows["strength"])
        )

        interacting_neighbors = set()
        total_interactions = 0

        # ---------- 遍历 KNN ----------
        for neighbor in nearest_neighbors:

            # ===== self 特判 =====
            if neighbor == cell_id:
                if neighbor not in ligand_strength:
                    continue  # self 无交流，直接跳过
                strength = ligand_strength[neighbor]
            else:
                strength = ligand_strength.get(neighbor, 0.0)

            # ===== 计算权重 =====
            if strength > 0:
                weight = 1.0 + math.log(1.0 + strength)
                interacting_neighbors.add(neighbor)
                total_interactions += 1
            else:
                weight = 1.0

            # ===== 存有向边 cell_id -> neighbor =====
            rows.append(cell_id - 1)
            cols.append(neighbor - 1)
            data.append(round(weight, 2))

        # ---------- 统计指标 ----------
        results.append({
            "cell_id": cell_id,
            "total_neighbors": n_neighbors,
            "interaction_ratio": len(interacting_neighbors) / n_neighbors,
            "total_interactions": total_interactions
        })

    # ===== 构建稀疏矩阵 =====
    adj = coo_matrix((data, (rows, cols)), shape=(num_cells, num_cells))

    save_sparse_matrix(adj, output_matrix_file,num_cells)

    results_df = pd.DataFrame(results)
    save_results_to_csv(results_df, output_csv_file)

    return results_df

