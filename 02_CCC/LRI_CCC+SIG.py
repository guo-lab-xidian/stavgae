import os
import numpy as np
from scipy import sparse
from scipy.io import mmread
from multiprocessing import Pool, cpu_count
import logging
from multiprocessing import freeze_support
# 设置日志记录
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def write_mtx_with_precision(target, a, precision=4):
    with open(target, 'w') as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python\n")
        coo = a.tocoo()
        f.write(f"{coo.shape[0]} {coo.shape[1]} {coo.nnz}\n")
        for i, j, v in zip(coo.row, coo.col, coo.data):
            formatted_value = f"{v:.{precision}f}"
            f.write(f"{i + 1} {j + 1} {formatted_value}\n")


def lri_permutation_test_and_save(args):
    matrix_path, num_permutations, output_dir, precision = args
    logging.info(f"开始处理文件: {matrix_path}")

    matrix_sparse = mmread(matrix_path).tocoo()
    logging.info(f"文件 {matrix_path} 读取成功，矩阵形状: {matrix_sparse.shape}")

    rows, cols, values = matrix_sparse.row, matrix_sparse.col, matrix_sparse.data
    values_cpu = np.asarray(values)
    num_values = len(values)
    p_values = np.ones(num_values, dtype=np.float32)

    rng = np.random.default_rng()
    for perm_idx in range(num_permutations):
        permuted_indices = rng.permutation(num_values)
        permuted_values = values_cpu[permuted_indices]
        p_values += np.abs(permuted_values) >= np.abs(values_cpu)
        if (perm_idx + 1) % 100 == 0:
            logging.info(f"文件 {matrix_path}: 已完成 {perm_idx + 1}/{num_permutations} 次置换")

    p_values = p_values / num_permutations
    significant_mask = p_values < 0.005
    significant_values = values_cpu * significant_mask

    nonzero_mask = significant_values != 0
    filtered_rows = rows[nonzero_mask]
    filtered_cols = cols[nonzero_mask]
    filtered_values = significant_values[nonzero_mask]

    significant_lris_sparse = sparse.coo_matrix(
        (filtered_values, (filtered_rows, filtered_cols)),
        shape=matrix_sparse.shape
    ).tocsr()

    original_name = os.path.splitext(os.path.basename(matrix_path))[0]
    mtx_path = os.path.join(output_dir, f"{original_name}_significant.mtx")
    npy_path = os.path.join(output_dir, f"{original_name}_pvalues.npy")

    write_mtx_with_precision(mtx_path, significant_lris_sparse, precision=precision)
    np.save(npy_path, p_values)

    logging.info(f"文件 {matrix_path} 处理完成: 显著LRI数量 {np.sum(significant_mask)} 保存至 {mtx_path}")


def process_multiple_sparse_lri_matrices(input_dir, output_dir='lri_results_sparse', num_permutations=1000, precision=2):
    os.makedirs(output_dir, exist_ok=True)
    mtx_files = [os.path.join(input_dir, f) for f in os.listdir(input_dir) if f.endswith('.mtx')]
    logging.info(f"找到 {len(mtx_files)} 个文件待处理")

    args_list = [(matrix_path, num_permutations, output_dir, precision) for matrix_path in mtx_files]
    with Pool(processes=min(cpu_count(), 8)) as pool:
        pool.map(lri_permutation_test_and_save, args_list)
