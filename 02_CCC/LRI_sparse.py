import os
import pandas as pd
from scipy import sparse
from multiprocessing import Pool, cpu_count
import logging

# 设置日志记录
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def convert_single_csv_to_sparse(args):
    """
    将单个CSV文件转换为稀疏矩阵并保存为MTX格式q，值保留4位小数。

    参数:
    - input_path: 输入的CSV文件路径
    - output_path: 输出的MTX文件路径
    """
    input_path, output_path = args
    logging.info(f"正在处理: {input_path}")
    # 读取CSV文件
    df = pd.read_csv(input_path, index_col=0)
    # 转换为稀疏矩阵（float16精度，保留4位小数）
    sparse_matrix = sparse.csr_matrix(df.values.astype('float16'))

    # 自定义保存函数以保留4位小数
    def write_with_precision(target, a, precision=4):
        with open(target, 'w') as f:
            # 写入MatrixMarket头信息
            f.write("%%MatrixMarket matrix coordinate real general\n")
            f.write("% Generated by Python\n")
            # 获取稀疏矩阵的COO表示
            coo = a.tocoo()
            # 写入矩阵的维度和非零元素数量
            f.write(f"{coo.shape[0]} {coo.shape[1]} {coo.nnz}\n")
            # 写入每个非零元素，保留指定精度
            for i, j, v in zip(coo.row, coo.col, coo.data):
                f.write(f"{i + 1} {j + 1} {format(v, f'.{precision}f')}\n")

    # 保存为MTX文件
    write_with_precision(output_path, sparse_matrix)
    return f"已转换: {input_path} -> {output_path}"


def convert_csv_to_sparse(input_dir, output_dir):
    """
    将文件夹中的CSV矩阵文件转换为稀疏矩阵并保存为MTX格式，支持多进程，值保留4位小数。

    参数:
    - input_dir: 包含CSV文件的输入目录
    - output_dir: 保存MTX文件的输出目录
    """
    # 创建输出目录
    os.makedirs(output_dir, exist_ok=True)

    # 获取所有CSV文件
    csv_files = [
        f for f in os.listdir(input_dir)
        if f.endswith('.csv')
    ]

    print(f"找到 {len(csv_files)} 个CSV文件，开始转换...")

    # 准备输入和输出文件路径
    tasks = [
        (os.path.join(input_dir, csv_file),
         os.path.join(output_dir, os.path.splitext(csv_file)[0] + '.mtx'))
        for csv_file in csv_files
    ]

    # 使用多进程加速转换
    with Pool(processes=min(cpu_count(), 4)) as pool:  # 限制最多使用4个进程
        results = pool.map(convert_single_csv_to_sparse, tasks)

    # 打印结果
    for result in results:
        print(result)

    print("所有文件转换完成！")


