import pandas as pd
import numpy as np
import os
import logging
from concurrent.futures import ProcessPoolExecutor
from scipy import sparse

# 日志配置
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

# 全局变量，用于多进程初始化
global_expression_matrix = None
global_result_dir = None

def init_worker(expression_matrix, result_dir):
    global global_expression_matrix
    global global_result_dir
    global_expression_matrix = expression_matrix
    global_result_dir = result_dir

# 写入稀疏矩阵为 .mtx 文件（Matrix Market 格式）
def write_sparse_mtx(target, sparse_matrix, precision=4):
    with open(target, 'w') as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python\n")
        coo = sparse_matrix.tocoo()
        f.write(f"{coo.shape[0]} {coo.shape[1]} {coo.nnz}\n")
        for i, j, v in zip(coo.row, coo.col, coo.data):
            f.write(f"{i + 1} {j + 1} {format(v, f'.{precision}f')}\n")

# 处理单个 LRI 行
def calculate_lri_for_row(row):
    global global_expression_matrix, global_result_dir

    logging.info(f"Processing LRI row: {row.name}")

    # 获取配体和受体
    ligands = [col for col in row.index if col.startswith('ligand') and pd.notna(row[col])]
    receptors = [col for col in row.index if col.startswith('receptor') and pd.notna(row[col])]
    valid_ligands = [row[col] for col in ligands]
    valid_receptors = [row[col] for col in receptors]

    L_matrix = global_expression_matrix.loc[valid_ligands].values
    R_matrix = global_expression_matrix.loc[valid_receptors].values

    # 几何均值
    L_geo = np.prod(L_matrix, axis=0) ** (1 / L_matrix.shape[0])
    R_geo = np.prod(R_matrix, axis=0) ** (1 / R_matrix.shape[0])

    # 非零位置
    nonzero_L = np.where(L_geo > 0)[0]
    nonzero_R = np.where(R_geo > 0)[0]

    # 外积 + 稀疏化
    row_idx, col_idx = np.meshgrid(nonzero_L, nonzero_R, indexing='ij')
    row_idx = row_idx.ravel()
    col_idx = col_idx.ravel()
    values = (L_geo[row_idx] * R_geo[col_idx]).astype(np.float16)

    sparse_mat = sparse.coo_matrix((values, (row_idx, col_idx)), shape=(len(L_geo), len(R_geo)))

    # 文件名：LRI_<rowID>.mtx
    filename = os.path.join(global_result_dir, f"LRI_{'_'.join(valid_ligands)}-{'_'.join(valid_receptors)}.mtx")
    write_sparse_mtx(filename, sparse_mat, precision=8)
    logging.info(f"Saved LRI matrix to: {filename}")
    return filename


# 并行主函数
def calculate_lri_scores_parallel(lri_data, expression_matrix,
                                   result_dir='D:/yxhu/空转/data/DLPFC/LRI_sparse/',
                                   n_cores=8):
    os.makedirs(result_dir, exist_ok=True)
    with ProcessPoolExecutor(max_workers=n_cores,
                             initializer=init_worker,
                             initargs=(expression_matrix, result_dir)) as executor:
        results = list(executor.map(calculate_lri_for_row, [row for _, row in lri_data.iterrows()]))

    logging.info("✅ 所有LRI稀疏矩阵已计算完毕！")
    return results

