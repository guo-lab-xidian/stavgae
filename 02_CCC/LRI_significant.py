import os
import numpy as np
from scipy import sparse
from scipy.io import mmread, mmwrite
from multiprocessing import Pool, cpu_count
import logging

# 设置日志记录
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')


def write_mtx_with_precision(target, a, precision=4):
    """
    自定义函数，用于以指定的精度和格式将稀疏矩阵保存为MTX格式，避免科学计数法。
    """
    with open(target, 'w') as f:
        # 写入MatrixMarket头信息
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write("% Generated by Python\n")
        # 获取稀疏矩阵的COO表示
        coo = a.tocoo()
        # 写入矩阵的维度和非零元素数量
        f.write(f"{coo.shape[0]} {coo.shape[1]} {coo.nnz}\n")
        # 写入每个非零元素，保留指定精度，避免科学计数法
        for i, j, v in zip(coo.row, coo.col, coo.data):
            formatted_value = f"{v:.{precision}f}"
            f.write(f"{i + 1} {j + 1} {formatted_value}\n")


def lri_permutation_test_cpu(args):
    """
    对单个LRI稀疏矩阵进行置换检验（使用CPU）。
    参数:
    - matrix_path: MTX 文件路径
    - num_permutations: 随机置换次数
    返回:
    - 显著LRI的稀疏矩阵（仅保留非零显著值）
    - p值矩阵（NumPy格式）
    """
    matrix_path, num_permutations = args
    logging.info(f"开始处理文件: {matrix_path}")

    # 读取 MTX 文件并转换为稀疏矩阵
    matrix_sparse = mmread(matrix_path).tocoo()
    logging.info(f"文件 {matrix_path} 读取成功，矩阵形状: {matrix_sparse.shape}")

    # 提取稀疏矩阵的行、列和值
    rows, cols, values = matrix_sparse.row, matrix_sparse.col, matrix_sparse.data

    # 转换为 NumPy 数组
    values_cpu = np.asarray(values)

    # 初始化 p 值
    num_values = len(values)
    p_values = np.ones(num_values, dtype=np.float32)

    # 进行随机置换
    for perm_idx in range(num_permutations):
        # 对非零元素进行随机置换
        permuted_indices = np.random.permutation(num_values)
        permuted_values = values_cpu[permuted_indices]

        # 计算置换分布中的统计值
        p_values += np.abs(permuted_values) >= np.abs(values_cpu)

        if (perm_idx + 1) % 100 == 0:
            logging.info(f"文件 {matrix_path}: 已完成 {perm_idx + 1}/{num_permutations} 次置换")

    # 归一化 p 值
    p_values = p_values / num_permutations

    # 标记显著值
    significant_mask = p_values < 0.05
    significant_values = values_cpu * significant_mask

    # 过滤掉显式的 0 值
    nonzero_mask = significant_values != 0
    filtered_rows = rows[nonzero_mask]
    filtered_cols = cols[nonzero_mask]
    filtered_values = significant_values[nonzero_mask]


    # 构建显著稀疏矩阵
    significant_lris_sparse = sparse.coo_matrix(
        (filtered_values, (filtered_rows, filtered_cols)),
        shape=matrix_sparse.shape
    ).tocsr()

    logging.info(f"文件 {matrix_path} 处理完成: 显著LRI数量 {np.sum(significant_mask)}")

    return significant_lris_sparse, p_values, matrix_path

def process_multiple_sparse_lri_matrices(
        input_dir,
        output_dir='lri_results_sparse',
        num_permutations=1000,
        precision=2
):
    """
    处理指定目录下的多个稀疏LRI分数矩阵（使用CPU）。

    参数:
    - input_dir: 包含MTX文件的输入目录
    - output_dir: 结果输出目录
    - num_permutations: 随机置换次数
    - precision: 输出值的小数位数
    """
    # 创建输出目录
    os.makedirs(output_dir, exist_ok=True)

    # 获取所有MTX文件
    mtx_files = [
        os.path.join(input_dir, f)
        for f in os.listdir(input_dir)
        if f.endswith('.mtx')
    ]

    logging.info(f"找到 {len(mtx_files)} 个文件待处理")

    # 准备参数
    args_list = [
        (matrix_path, num_permutations)
        for matrix_path in mtx_files
    ]

    # 使用进程池并行处理
    with Pool(processes=min(cpu_count(), 8)) as pool:
        results = pool.map(lri_permutation_test_cpu, args_list)

    # 保存结果
    for significant_lris_sparse, p_values, original_path in results:
        # 保留原始文件名
        original_name = os.path.splitext(os.path.basename(original_path))[0]
        mtx_path = os.path.join(output_dir, f"{original_name}_significant.mtx")

        # 保存显著LRI稀疏矩阵为MTX格式
        write_mtx_with_precision(mtx_path, significant_lris_sparse, precision=precision)
        # 保存p值矩阵
        np.save(
            os.path.join(output_dir, f"{original_name}_pvalues.npy"),
            p_values
        )

        logging.info(f"矩阵 {original_name} 的结果已保存为: {mtx_path}")


